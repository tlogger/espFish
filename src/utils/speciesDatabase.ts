export type SpeciesCategory = 'ROCKFISH' | 'PELAGIC' | 'BENTHIC' | 'CEPHALOPOD' | 'SEA_BREAM';
export type BottomType = 'ROCK_REEF' | 'SAND_FLAT' | 'MUD_FLAT' | 'MIXED' | 'OPEN_WATER';
export type ActivityPeriod = 'NOCTURNAL' | 'DIURNAL' | 'CREPUSCULAR';
export type CurrentPreference = 'STRONG' | 'MODERATE' | 'SLACK_GENTLE';
export type WaterLayer = 'SURFACE' | 'MID' | 'BOTTOM' | 'ALL';
export type CoastRegion = 'WEST' | 'SOUTH' | 'EAST' | 'JEJU';
export type TimeRestriction = 'STRICT_DAY' | 'STRICT_NIGHT' | 'CREPUSCULAR_PEAK' | 'ALL_DAY';

export interface DailyActivityProfile {
  activeHours: number[]; // 활동 시간대 (0~23시)
  peakHours: number[]; // 최적 피크 시간대
  restriction: TimeRestriction; // STRICT_DAY(낮에만), STRICT_NIGHT(밤에만), CREPUSCULAR_PEAK(해창), ALL_DAY(전일)
  timeNote: string; // 시간대별 생태 설명
}

export interface SpeciesEcology {
  name: string;
  category: SpeciesCategory;
  categoryName: string; // 락피시, 회유성, 저서성, 두족류, 도미류
  bottomType: BottomType;
  bottomName: string; // 여밭/암초, 모래, 뻘/모래뻘, 복합, 조류물골
  activityPeriod: ActivityPeriod;
  activityName: string; // 야행성, 주행성, 여명/일몰 피딩형
  tempRange: {
    min: number; // 생존 한계 저수온
    optMin: number; // 최적 활성 하한
    optMax: number; // 최적 활성 상한
    max: number; // 생존 한계 고수온
  };
  peakMonths: number[]; // 주 낚시 시즌 월 (1~12)
  currentPref: CurrentPreference;
  currentPrefName: string; // 본류대(사리), 적당한 흐름, 완류(조금~약류)
  description: string;

  // === v2.0 신규 상세 필드 (선택적 확장, 100% 하위호환) ===
  scientificName?: string; // 학명 (예: Sebastes schlegelii)
  waterLayer?: WaterLayer; // 주 유영 수층 (SURFACE 표층, MID 중층, BOTTOM 바닥층, ALL 전층)
  waterLayerName?: string; // 수층 한글 설명 (예: 바닥층~바닥 1m 위)
  regions?: CoastRegion[]; // 잘 잡히는 연안 권역
  regionNames?: string; // 잘 잡히는 대표 지역 한글 설명 (예: 서해 전역(태안/격포), 남해안)
  tastiestMonths?: number[]; // 가장 맛있는 제철 월 (1~12)
  tastiestDesc?: string; // 가장 맛있는 제철 설명 (예: 늦가을~겨울 살오름)
  minLengthCm?: number | null; // 법정 포획 금지 체장 (cm, null이면 규정 없음)
  minWeightG?: number | null; // 법정 포획 금지 체중 (g, 대문어 600g 등)
  lengthStandard?: 'TOTAL_LENGTH' | 'ANAL_LENGTH' | 'MANTLE_LENGTH' | 'WEIGHT' | 'NONE'; // 계측 기준 (전장, 항문장, 외투장, 체중)
  prohibitedPeriod?: string | null; // 법정 금어기 기간 텍스트 (null이면 없음)
  prohibitedNote?: string; // 금어기/금지체장 세부 규정 및 지자체 예외 고시
  recommendedBait?: string; // 초보자용 대표 추천 미끼/루어 요약
  dailyProfile?: DailyActivityProfile; // 어종별 일중 활동 시간대 프로필
}

